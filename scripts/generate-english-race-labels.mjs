// Builds src/lib/englishRaceLabels.generated.ts: native race type / distance
// labels (all markets) mapped to their English equivalents from merged_index_int.yaml.
// Run: node scripts/generate-english-race-labels.mjs
import fs from 'node:fs';
import path from 'node:path';
import yaml from 'js-yaml';

const root = path.resolve('data/countries');
const map = {};
const add = (native, en) => {
  if (typeof native !== 'string' || typeof en !== 'string') return;
  const k = native.trim().toLowerCase();
  if (!k || k === en.trim().toLowerCase()) return;
  if (!(k in map)) map[k] = en.trim();
};
for (const cc of fs.readdirSync(root).sort()) {
  const nf = path.join(root, cc, 'index.yaml');
  const ef = path.join(root, cc, 'merged_index_int.yaml');
  if (!fs.existsSync(nf) || !fs.existsSync(ef)) continue;
  const n = yaml.load(fs.readFileSync(nf, 'utf8')) ?? {};
  const e = yaml.load(fs.readFileSync(ef, 'utf8')) ?? {};
  for (const key of ['type_options', 'distance_mapping', 'verbose_local_distance_mapping']) {
    for (const [k, v] of Object.entries(n[key] ?? {})) add(v, (e[key] ?? {})[k]);
  }
  (n.distance_units ?? []).forEach((u, i) => add(u?.label, e.distance_units?.[i]?.label));
}
const out = `// Generated by scripts/generate-english-race-labels.mjs. Do not edit by hand.\nexport const ENGLISH_RACE_LABELS: Record<string, string> = ${JSON.stringify(map, null, 2)};\n`;
fs.writeFileSync('src/lib/englishRaceLabels.generated.ts', out);
console.log(`wrote ${Object.keys(map).length} labels`);
