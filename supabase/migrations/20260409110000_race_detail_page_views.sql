create or replace function public.get_race_detail_page_view_rankings(
  p_country_code text,
  p_days integer default 30,
  p_limit integer default 100
) returns table (
  domain_name text,
  page_views_last_30_days bigint,
  last_view_at timestamptz
)
language sql
stable
security definer
set search_path = public, crm
as $$
with normalized as (
  select
    nullif(lower(btrim(coalesce(p_country_code, ''))), '') as country_code,
    greatest(coalesce(p_days, 30), 1) as day_count,
    least(greatest(coalesce(p_limit, 100), 1), 5000) as row_limit
)
select
  views.domain_name,
  count(*)::bigint as page_views_last_30_days,
  max(views.created_at) as last_view_at
from
  crm.race_detail_page_views views
  cross join normalized
where
  normalized.country_code is not null
  and views.country_code = normalized.country_code
  and views.created_at >= now() - make_interval(days => normalized.day_count)
group by
  views.domain_name
order by
  page_views_last_30_days desc,
  last_view_at desc,
  views.domain_name asc
limit (
  select
    row_limit
  from
    normalized
);
$$;

revoke all on function public.get_race_detail_page_view_rankings(text, integer, integer) from public;
revoke all on function public.get_race_detail_page_view_rankings(text, integer, integer) from anon;
revoke all on function public.get_race_detail_page_view_rankings(text, integer, integer) from authenticated;

grant execute on function public.get_race_detail_page_view_rankings(text, integer, integer) to service_role;
