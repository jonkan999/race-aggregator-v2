create schema if not exists crm;

create table if not exists crm.race_detail_page_views (
  id bigint generated by default as identity primary key,
  site_key text not null,
  site_name text,
  country_code text not null,
  locale text,
  domain_name text not null,
  page_path text,
  page_url text,
  referrer text,
  created_at timestamptz not null default now()
);

create index if not exists race_detail_page_views_country_created_idx
  on crm.race_detail_page_views (country_code, created_at desc);

create index if not exists race_detail_page_views_domain_created_idx
  on crm.race_detail_page_views (domain_name, created_at desc);

revoke all on crm.race_detail_page_views from public;
revoke all on crm.race_detail_page_views from anon;
revoke all on crm.race_detail_page_views from authenticated;

create or replace function public.record_race_detail_page_view(
  p_site_key text default null,
  p_site_name text default null,
  p_country_code text default null,
  p_locale text default null,
  p_domain_name text default null,
  p_page_path text default null,
  p_page_url text default null,
  p_referrer text default null
) returns void
language plpgsql
security definer
set search_path = public, crm
as $$
begin
  if btrim(coalesce(p_site_key, '')) = '' then
    return;
  end if;

  if btrim(coalesce(p_country_code, '')) = '' then
    return;
  end if;

  if btrim(coalesce(p_domain_name, '')) = '' then
    return;
  end if;

  insert into crm.race_detail_page_views (
    site_key,
    site_name,
    country_code,
    locale,
    domain_name,
    page_path,
    page_url,
    referrer
  ) values (
    p_site_key,
    nullif(btrim(coalesce(p_site_name, '')), ''),
    lower(btrim(p_country_code)),
    nullif(lower(btrim(coalesce(p_locale, ''))), ''),
    lower(btrim(p_domain_name)),
    nullif(btrim(coalesce(p_page_path, '')), ''),
    nullif(btrim(coalesce(p_page_url, '')), ''),
    nullif(btrim(coalesce(p_referrer, '')), '')
  );
end;
$$;

